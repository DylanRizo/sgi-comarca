import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXPECTED_SOURCE_SHA256 =
  '1472aafa2561df5e3293aee252aee3ca660c12b399a283cf808bb01b39be388b';
const EXPECTED_ENTRY_COUNT = 483;

const inputPaths = process.argv.slice(2);
if (inputPaths.length !== 1) {
  throw new Error('Usage: node generate-common-passwords.mjs <source-file>');
}

const inputPath = resolve(inputPaths[0]);
const source = await readFile(inputPath);
const sourceSha256 = createHash('sha256').update(source).digest('hex');
if (sourceSha256 !== EXPECTED_SOURCE_SHA256) {
  throw new Error(
    'The SecLists source checksum does not match the pinned file.',
  );
}

const entries = [
  ...new Set(
    source
      .toString('utf8')
      .split(/\r?\n/u)
      .map((value) => value.normalize('NFC').toLocaleLowerCase('und'))
      .filter((value) => {
        const length = [...value].length;
        return length >= 12 && length <= 128;
      }),
  ),
];

if (entries.length !== EXPECTED_ENTRY_COUNT) {
  throw new Error(
    `Expected ${EXPECTED_ENTRY_COUNT} generated entries, received ${entries.length}.`,
  );
}

const contentSha256 = createHash('sha256')
  .update(entries.join('\n'), 'utf8')
  .digest('hex');
const moduleText = `// Generated by generate-common-passwords.mjs. Do not edit manually.
export const COMMON_PASSWORD_SOURCE_SHA256 = '${sourceSha256}';
export const COMMON_PASSWORD_CONTENT_SHA256 = '${contentSha256}';
export const COMMON_PASSWORD_ENTRY_COUNT = ${entries.length};

export const commonPasswords = new Set<string>(${JSON.stringify(entries, null, 2)});
`;

const currentDirectory = dirname(fileURLToPath(import.meta.url));
await writeFile(
  resolve(currentDirectory, 'common-passwords.generated.ts'),
  moduleText,
  'utf8',
);

console.log(
  JSON.stringify({
    contentSha256,
    entries: entries.length,
    sourceSha256,
  }),
);
